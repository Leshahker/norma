function matchHealth(text) {
  const source = String(text || "").toLowerCase().replace(/ё/g, "е");
  if (!source.trim()) return [];
  const ids = [];
  HEALTH_HINTS.forEach(pair => {
    if (pair[0].test(source) && ids.indexOf(pair[1]) < 0) ids.push(pair[1]);
  });
  SUPPRESS.forEach(pair => {
    if (ids.indexOf(pair[0]) < 0) return;
    pair[1].forEach(id => {
      const at = ids.indexOf(id);
      if (at >= 0) ids.splice(at, 1);
    });
  });
  return ids.filter(id => HEALTH_BY[id]);
}
