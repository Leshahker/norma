function foodText(s) {
  return String(s || "").toLowerCase().replace(/ё/g, "е");
}

function searchFoods(query) {
  const q = foodText(query).trim();
  if (q.length < 2) return [];
  return FOODS.map(item => {
    const name = foodText(item.n);
    const at = name.indexOf(q);
    if (at < 0) return null;
    let score = 12 - Math.min(at, 10);
    if (name.indexOf(q) === 0) score += 6;
    if (item.where === "by") score += 2;
    if (item.where === "ru") score += 1;
    return { item: item, score: score };
  }).filter(Boolean).sort((a, b) => b.score - a.score || a.item.n.length - b.item.n.length).slice(0, 18).map(row => row.item);
}

function foodByCode(code) {
  const clean = String(code || "").replace(/\D/g, "");
  return FOODS.find(item => item.code === clean) || null;
}

